#!/usr/bin/env python3
"""Generate indexes/CODE_INDEX.md: a structural index of the repository.

Walks services, packages, workers and the data layer and records what
exists -- routes, exported types, line counts and test counts -- so the
tree can be cross-checked against GOVERNANCE.md without re-reading it.
"""
import os
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROUTE = re.compile(r'HandleFunc\("([^"]+)"')
GOFUNC = re.compile(r'^func (?:\([^)]*\) )?([A-Z]\w+)\(', re.M)
GOTYPE = re.compile(r'^type ([A-Z]\w+) ', re.M)
TESTFN = re.compile(r'^func (Test\w+)\(', re.M)


def read(p):
    try:
        return p.read_text(errors="replace")
    except OSError:
        return ""


def scan(d):
    """Collect routes, types, LOC and test counts for one component."""
    src = loc = tests = 0
    routes, types = [], []
    for f in sorted(d.rglob("*.go")) + sorted(d.rglob("*.py")):
        text = read(f)
        n = text.count("\n")
        if f.name.endswith(("_test.go", "test_.py")) or f.name.startswith("test_"):
            tests += len(TESTFN.findall(text)) + text.count("def test_")
            continue
        loc += n
        src += 1
        routes += ROUTE.findall(text)
        types += GOTYPE.findall(text)
    return dict(files=src, loc=loc, tests=tests,
                routes=sorted(set(routes)), types=sorted(set(types)))


def section(title, base):
    out = [f"\n## {title}\n"]
    if not base.is_dir():
        return out
    for d in sorted(p for p in base.iterdir() if p.is_dir()):
        s = scan(d)
        if not s["files"]:
            continue
        out.append(f"### `{base.name}/{d.name}`\n")
        out.append(f"- {s['files']} source files, {s['loc']} LOC, {s['tests']} tests")
        if s["routes"]:
            out.append("- Routes:")
            out += [f"  - `{r}`" for r in s["routes"]]
        if s["types"]:
            shown = ", ".join(f"`{t}`" for t in s["types"][:14])
            more = "" if len(s["types"]) <= 14 else f" (+{len(s['types']) - 14} more)"
            out.append(f"- Exported types: {shown}{more}")
        out.append("")
    return out


def main():
    try:
        rev = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                             capture_output=True, text=True, check=True).stdout.strip()
    except (subprocess.CalledProcessError, OSError):
        rev = "unknown"

    lines = [
        "# Code Index",
        "",
        f"Generated by `scripts/generate_code_index.py` at commit `{rev}`.",
        "Regenerate with `make code-index`. Do not edit by hand.",
        "",
        "Structural inventory only: it records what exists, not whether it",
        "satisfies `GOVERNANCE.md`.",
    ]
    for title, base in (("Services", ROOT / "services"),
                        ("Packages", ROOT / "packages"),
                        ("Workers", ROOT / "workers"),
                        ("Adapters", ROOT / "adapters")):
        lines += section(title, base)

    lines.append("\n## Data layer\n")
    for name, pat in (("Migrations", "database/migrations/*.sql"),
                      ("RLS policies", "database/policies/*.sql"),
                      ("Schemas", "schemas/**/*.json"),
                      ("ADRs", "docs/adr/*.md")):
        found = sorted(ROOT.glob(pat))
        lines.append(f"### {name} ({len(found)})\n")
        lines += [f"- `{p.relative_to(ROOT)}`" for p in found]
        lines.append("")

    out = ROOT / "indexes" / "CODE_INDEX.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out.relative_to(ROOT)} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
