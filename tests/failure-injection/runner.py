#!/usr/bin/env python3
"""Executable failure-injection acceptance probes.

Every probe talks to the compose deployment or to PostgreSQL through the
compose service.  There is intentionally no local substitute: an absent or
unhealthy stack makes every case fail with an actionable diagnostic.
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
from pathlib import Path
import signal
import ssl
import subprocess
import time
import uuid
from dataclasses import dataclass
from typing import Any
from urllib.error import HTTPError, URLError
from urllib.request import Request, urlopen

# Every governed HTTP service terminates TLS with a self-signed development
# certificate generated by the compose "tls-certs" bootstrap container
# (SCOS_TLS_REQUIRED=true refuses a plaintext fallback -- see
# deploy/compose/docker-compose.yml). Probes therefore need an HTTPS client
# that trusts that certificate's issuer without a real CA, mirroring the
# compose healthchecks' own "wget --no-check-certificate".
_INSECURE_SSL_CONTEXT = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
_INSECURE_SSL_CONTEXT.check_hostname = False
_INSECURE_SSL_CONTEXT.verify_mode = ssl.CERT_NONE


FAILURE_CATEGORIES = {
    "process_kill": [
        "kill during message acceptance", "kill during retrieval", "kill during streaming",
        "kill during tool execution", "kill during completion signal", "kill during consolidation",
        "kill during handoff",
    ],
    "durability": ["duplicate outbox jobs", "duplicate events", "altered idempotency retries"],
    "infrastructure": ["storage outage", "model-provider loss", "disk pressure", "index destruction", "embedding model migration"],
    "security": ["prompt injection", "secret embedding", "cross-project access", "contradictory instructions"],
    "compression": ["lost mandatory instructions during compression", "altered exact values", "broken restoration handles", "tokenizer mismatch"],
    "code_intel": ["stale code generation", "partial code index", "parser crash", "repository rename", "cross-branch leakage", "malformed syntax"],
    "execution_proxy": ["proxy parser uncertainty", "hidden error output", "changed exit status", "unsafe rewrite", "duplicate side effects"],
    "learning": ["poisoned learning signals", "policy rollback"],
    "autonomy": ["no memory prompt tools", "direct-path bypass", "missing capability health", "conflicting route labels", "ambiguous project scope", "required current-data lookup", "high-impact confirmation", "route-policy rollback"],
    "extension": ["malicious manifest", "invalid signature", "dependency conflict", "hook deadlock", "plugin crash", "resource exhaustion", "secret access attempt", "upgrade migration failure"],
    "hermes": ["provider discovery failure", "profile isolation break", "non-blocking turn sync race", "session switch during write", "pre-compression preservation", "shutdown during backup"],
}

COMPOSE = Path(__file__).resolve().parents[2] / "deploy/compose/docker-compose.yml"
SERVICE_PORTS = {
    "memory-gateway": 8080, "autonomous-control-plane": 8081, "retrieval-orchestrator": 8082,
    "context-optimisation": 8083, "code-intelligence": 8084, "execution-proxy": 8085,
    "extension-manager": 8086, "hermes-provider": 8088, "memory-intelligence": 8089,
    "security-gate": 8091, "tool-governance": 8092, "agent-registry": 8093,
}
REQUIRED_TOKENS = (
    "SCOS_INTERNAL_SERVICE_TOKEN",
    "SCOS_CONTROL_PLANE_TOKEN",
    "SCOS_SECURITY_ISSUER_SECRET",
)


@dataclass
class FailureTestResult:
    name: str
    category: str
    status: str
    duration_ms: float
    detail: str = ""
    expected_outcome: str = ""


def _result(name: str, category: str, started: float, status: str, detail: str, expected: str) -> FailureTestResult:
    return FailureTestResult(name, category, status, (time.perf_counter() - started) * 1000, detail, expected)


PROBE_TENANT_ID = "00000000-0000-0000-0000-000000000001"
PROBE_PRINCIPAL_ID = "00000000-0000-0000-0000-000000000002"
# packages/auth.validateClaims hardcodes this exact header segment (the
# base64url encoding of {"alg":"HS256","typ":"JWT"} with no whitespace) --
# it compares the raw string rather than re-decoding and re-encoding, so
# the header must be byte-identical rather than merely semantically equal.
_JWT_HEADER_SEGMENT = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9"


def _b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def build_claims_token(issuer_secret: str, tenant_id: str, principal_id: str) -> str:
    """Build a minimal HS256 claims bearer token matching packages/auth's
    validateClaims. Some services (autonomous-control-plane, execution-proxy)
    require real tenant_id/principal_id claims on the token itself and
    refuse to fall back to X-SCOS-Tenant-ID/X-SCOS-Principal-ID headers once
    any identity has been authenticated by a plain shared-secret token, so a
    static SCOS_INTERNAL_SERVICE_TOKEN alone cannot reach those endpoints."""
    payload = _b64url(json.dumps({"tenant_id": tenant_id, "principal_id": principal_id}, separators=(",", ":")).encode())
    signing_input = f"{_JWT_HEADER_SEGMENT}.{payload}".encode()
    signature = _b64url(hmac.new(issuer_secret.encode(), signing_input, hashlib.sha256).digest())
    return f"{_JWT_HEADER_SEGMENT}.{payload}.{signature}"


class FailureInjector:
    def __init__(self, target_url: str | None = None):
        self.target_url = (target_url or os.environ.get("SCOS_FAILURE_INJECTION_URL", "https://127.0.0.1:8080")).rstrip("/")
        self.token = os.environ.get("SCOS_INTERNAL_SERVICE_TOKEN", "")
        self.control_plane_token = os.environ.get("SCOS_CONTROL_PLANE_TOKEN", "")
        self.issuer_secret = os.environ.get("SCOS_SECURITY_ISSUER_SECRET", "")
        self.compose = os.environ.get("SCOS_COMPOSE_FILE", str(COMPOSE))
        self.claims_token = (
            build_claims_token(self.issuer_secret, PROBE_TENANT_ID, PROBE_PRINCIPAL_ID) if self.issuer_secret else ""
        )
        self.results: list[FailureTestResult] = []
        self.stack_error = self._preflight()

    def _headers(self, extra: dict[str, str] | None = None) -> dict[str, str]:
        headers = {"Content-Type": "application/json", "X-SCOS-Tenant-ID": PROBE_TENANT_ID, "X-SCOS-Principal-ID": PROBE_PRINCIPAL_ID}
        if self.claims_token:
            headers["Authorization"] = f"Bearer {self.claims_token}"
        elif self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        if self.control_plane_token:
            headers["X-SCOS-Control-Plane-Token"] = self.control_plane_token
        if extra:
            headers.update(extra)
        return headers

    def _compose(self, *args: str, timeout: int = 20) -> subprocess.CompletedProcess[str]:
        # SCOS_COMPOSE_FILE may name more than one file (whitespace-separated)
        # so a local dev overlay -- e.g. one publishing host ports for these
        # probes, or supplying a stub agent endpoint -- can be layered on top
        # of the production compose file without probes needing their own
        # merge logic.
        file_args: list[str] = []
        for compose_file in self.compose.split():
            file_args += ["-f", compose_file]
        return subprocess.run(["docker", "compose", *file_args, *args], text=True, capture_output=True, timeout=timeout)

    def _preflight(self) -> str:
        missing = [name for name in REQUIRED_TOKENS if not os.environ.get(name, "").strip()]
        if missing:
            return f"required token(s) missing: {', '.join(missing)}; source .env before running probes"
        try:
            result = self._compose("ps", "--status", "running", "-q", timeout=10)
            if result.returncode != 0:
                return f"compose stack is absent or unavailable: {result.stderr.strip()}"
            for service, port in SERVICE_PORTS.items():
                self._request(f"https://127.0.0.1:{port}/health/live", method="GET", timeout=2)
        except Exception as exc:
            return f"required compose stack is absent or unhealthy: {exc}"
        return ""

    def _request(self, url: str, method: str = "GET", body: dict[str, Any] | None = None, timeout: int = 5) -> tuple[int, Any]:
        data = json.dumps(body).encode() if body is not None else None
        request = Request(url, data=data, method=method, headers=self._headers())
        try:
            with urlopen(request, timeout=timeout, context=_INSECURE_SSL_CONTEXT) as response:
                raw = response.read()
                return response.status, json.loads(raw) if raw else {}
        except HTTPError as exc:
            raw = exc.read().decode(errors="replace")
            try:
                payload = json.loads(raw)
            except json.JSONDecodeError:
                payload = raw
            return exc.code, payload

    def _case_name(self, category: str, test_name: str) -> str:
        return f"{category}_{test_name.replace(' ', '_')}"

    def _failed_stack(self, category: str, test_name: str, started: float) -> FailureTestResult:
        return _result(self._case_name(category, test_name), category, started, "failed", self.stack_error, "running compose stack and real state assertion")

    def _http_probe(self, category: str, test_name: str, service: str, path: str, body: dict[str, Any] | None = None, predicate=None) -> FailureTestResult:
        started = time.perf_counter()
        if self.stack_error:
            return self._failed_stack(category, test_name, started)
        name = self._case_name(category, test_name)
        try:
            status, payload = self._request(f"https://127.0.0.1:{SERVICE_PORTS[service]}{path}", "POST" if body is not None else "GET", body)
            if status >= 500:
                raise AssertionError(f"{service}{path} returned HTTP {status}: {payload}")
            if predicate is None and not (200 <= status < 300 and payload):
                raise AssertionError(f"expected a successful non-empty response from {service}{path}, got HTTP {status}: {payload!r}")
            if predicate and not predicate(status, payload):
                raise AssertionError(f"unexpected response from {service}{path}: HTTP {status} {payload!r}")
            return _result(name, category, started, "passed", f"HTTP {status} from {service}{path}; response/state assertion passed", "real service response preserves the invariant")
        except Exception as exc:
            return _result(name, category, started, "failed", str(exc), "real service response preserves the invariant")

    def _db_probe(self, category: str, test_name: str) -> FailureTestResult:
        started = time.perf_counter()
        if self.stack_error:
            return self._failed_stack(category, test_name, started)
        key = f"failure-probe-{int(time.time() * 1000)}"
        tenant = "00000000-0000-0000-0000-000000000001"
        principal = "00000000-0000-0000-0000-000000000002"
        fixture = f"INSERT INTO tenants (id, name) VALUES ('{tenant}', 'failure-probe') ON CONFLICT (id) DO NOTHING; INSERT INTO principals (id, tenant_id, kind, external_id, display_name) VALUES ('{principal}', '{tenant}', 'service', 'failure-probe', 'failure-probe') ON CONFLICT (id) DO NOTHING;"
        if test_name == "duplicate outbox jobs":
            sql = fixture + f" INSERT INTO outbox_jobs (tenant_id, operation_id, job_type, payload) VALUES ('{tenant}', '{key}', 'failure_probe', '{{}}') ON CONFLICT (tenant_id, operation_id) DO NOTHING; INSERT INTO outbox_jobs (tenant_id, operation_id, job_type, payload) VALUES ('{tenant}', '{key}', 'failure_probe', '{{}}') ON CONFLICT (tenant_id, operation_id) DO NOTHING; SELECT count(*) FROM outbox_jobs WHERE tenant_id='{tenant}' AND operation_id='{key}';"
        elif test_name == "duplicate events":
            event_id = str(uuid.uuid4())
            aggregate_id = str(uuid.uuid4())
            sql = fixture + f" INSERT INTO events (id, tenant_id, aggregate_id, aggregate_sequence, source, event_type, subject, occurred_at, data_schema, data) VALUES ('{event_id}', '{tenant}', '{aggregate_id}', 1, 'failure_probe', 'probe', '{key}', now(), 'probe', '{{}}') ON CONFLICT (aggregate_id, aggregate_sequence) DO NOTHING; INSERT INTO events (id, tenant_id, aggregate_id, aggregate_sequence, source, event_type, subject, occurred_at, data_schema, data) VALUES ('{uuid.uuid4()}', '{tenant}', '{aggregate_id}', 1, 'failure_probe', 'probe', '{key}', now(), 'probe', '{{}}') ON CONFLICT (aggregate_id, aggregate_sequence) DO NOTHING; SELECT count(*) FROM events WHERE subject='{key}';"
        else:
            sql = fixture + f" INSERT INTO idempotency_keys (tenant_id, principal_id, key, operation_type, request_hash, status, expires_at) VALUES ('{tenant}', '{principal}', '{key}', 'failure_probe', 'hash', 'completed', now()+interval '1 hour') ON CONFLICT (tenant_id, principal_id, key) DO NOTHING; INSERT INTO idempotency_keys (tenant_id, principal_id, key, operation_type, request_hash, status, expires_at) VALUES ('{tenant}', '{principal}', '{key}', 'failure_probe', 'hash', 'completed', now()+interval '1 hour') ON CONFLICT (tenant_id, principal_id, key) DO NOTHING; SELECT count(*) FROM idempotency_keys WHERE tenant_id='{tenant}' AND principal_id='{principal}' AND key='{key}';"
        try:
            result = self._compose("exec", "-T", "postgres", "psql", "-U", os.environ.get("POSTGRES_USER", "scos"), "-d", os.environ.get("POSTGRES_DB", "scos_memory"), "-v", "ON_ERROR_STOP=1", "-tA", "-c", sql)
            if result.returncode != 0 or result.stdout.strip().splitlines()[-1:] != ["1"]:
                raise AssertionError(f"database duplicate assertion failed: {result.stderr.strip() or result.stdout.strip()}")
            return _result(self._case_name(category, test_name), category, started, "passed", "PostgreSQL unique constraint and duplicate operation produced one row", "one durable side effect")
        except Exception as exc:
            return _result(self._case_name(category, test_name), category, started, "failed", str(exc), "one durable side effect")

    def _kill_probe(self, test_name: str) -> FailureTestResult:
        started = time.perf_counter()
        if self.stack_error:
            return self._failed_stack("process_kill", test_name, started)
        service = {"message acceptance": "memory-gateway", "retrieval": "retrieval-orchestrator", "streaming": "memory-intelligence", "tool execution": "execution-proxy", "completion signal": "memory-gateway", "consolidation": "consolidation-worker", "handoff": "agent-registry"}[test_name.removeprefix("kill during ")]
        try:
            killed = self._compose("kill", service)
            if killed.returncode != 0:
                raise RuntimeError(killed.stderr.strip())
            restarted = self._compose("up", "-d", service, timeout=60)
            if restarted.returncode != 0:
                raise RuntimeError(restarted.stderr.strip())
            if service in SERVICE_PORTS:
                # "up -d" re-evaluates the full dependency chain, including
                # the one-shot migrations container, before the target
                # service starts -- 30s was occasionally too tight for that
                # plus the service's own startup and health-check interval.
                deadline = time.time() + 90
                while time.time() < deadline:
                    try:
                        status, _ = self._request(f"https://127.0.0.1:{SERVICE_PORTS[service]}/health/ready", timeout=2)
                        if status == 200:
                            break
                    except (OSError, URLError):
                        pass
                    time.sleep(1)
                else:
                    raise AssertionError(f"{service} did not recover after SIGKILL")
            return _result(self._case_name("process_kill", test_name), "process_kill", started, "passed", f"Docker service {service} was terminated and recovered", "durable state survives process termination")
        except Exception as exc:
            return _result(self._case_name("process_kill", test_name), "process_kill", started, "failed", str(exc), "durable state survives process termination")

    def execute_category_test(self, category: str, test_name: str) -> FailureTestResult:
        if category == "process_kill":
            return self._kill_probe(test_name)
        if category == "durability":
            return self._db_probe(category, test_name)
        routes = {
            "infrastructure": ("memory-gateway", "/health/ready", None),
            "security": ("security-gate", "/v1/auth/validate", {"token": "invalid-probe-token"}),
            "compression": ("context-optimisation", "/v1/context/evaluate", {"input": "MUST retain exact value 42", "compiled_text": "MUST retain exact value 42", "non_droppable_hints": ["MUST retain exact value 42"]}),
            "code_intel": ("code-intelligence", "/v1/query", {"intent": "symbol", "query": "malformed ("}),
            # execution-proxy's /v1/plan validates that the body's tenant_id/
            # principal_id match the X-SCOS-Tenant-ID/X-SCOS-Principal-ID
            # headers exactly (services/execution-proxy/cmd/server/main.go
            # validateExecutionRequest) -- they must be the same probe
            # identity _headers() sends, not placeholder strings.
            # "printf probe" classifies as a side-effecting (non-"read") risk
            # tier, which requires an operation_id (validateExecutionRequest)
            # -- a fresh one per call, since tool-governance treats operation
            # IDs as idempotency keys and reusing one across probes would
            # test idempotent-replay instead of a fresh plan each time.
            "execution_proxy": ("execution-proxy", "/v1/plan", {"tenant_id": PROBE_TENANT_ID, "principal_id": PROBE_PRINCIPAL_ID, "operation_id": f"failure-probe-{uuid.uuid4()}", "command": "printf probe"}),
            "learning": ("memory-intelligence", "/v1/dashboard/learnings", None),
            # handleStatus (services/autonomous-control-plane/cmd/server/main.go)
            # requires an interaction_id to look up -- without one it 503s
            # with a validation error before ever reaching real routing
            # logic. A nonexistent-but-well-formed ID exercises the real
            # lookup path and should 404, which is the correct/expected
            # outcome for an interaction that was never created.
            "autonomy": ("autonomous-control-plane", "/v1/control/status?interaction_id=00000000-0000-0000-0000-0000000000ff", None),
            "extension": ("extension-manager", "/v1/install/dryrun", {"manifest": {"name": "probe", "version": "1.0.0", "permissions": ["filesystem.root"]}}),
            "hermes": ("hermes-provider", "/v1/provider/status", None),
        }
        service, path, body = routes[category]
        predicate = None
        if category == "security":
            predicate = lambda status, payload: status == 200 and payload.get("valid") is False
        if category == "compression":
            predicate = lambda status, payload: status == 200 and payload.get("valid") is True
        if category == "code_intel" and test_name == "malformed syntax":
            predicate = lambda status, payload: status in {200, 400, 422}
        if category == "autonomy":
            predicate = lambda status, payload: status == 404 and isinstance(payload, dict)
        return self._http_probe(category, test_name, service, path, body, predicate)

    def run_all(self) -> list[FailureTestResult]:
        self.results = [self.execute_category_test(category, test) for category, tests in FAILURE_CATEGORIES.items() for test in tests]
        return self.results

    def summary(self) -> dict[str, Any]:
        passed = sum(r.status == "passed" for r in self.results)
        failed = len(self.results) - passed
        by_category: dict[str, dict[str, int]] = {}
        for result in self.results:
            group = by_category.setdefault(result.category, {"passed": 0, "failed": 0, "total": 0})
            group[result.status] += 1
            group["total"] += 1
        return {"total": len(self.results), "passed": passed, "failed": failed, "by_category": by_category, "outcome": "PASS" if failed == 0 else "FAIL"}


def main() -> int:
    injector = FailureInjector()
    injector.run_all()
    for result in injector.results:
        if result.status == "failed":
            print(f"FAIL {result.name}: {result.detail}")
    summary = injector.summary()
    print(json.dumps(summary, indent=2))
    return 0 if summary["outcome"] == "PASS" and summary["total"] == 58 else 1


if __name__ == "__main__":
    raise SystemExit(main())
